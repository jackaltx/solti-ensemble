#!/usr/bin/env bash
#
# manage-feature.sh — Apply and manage features (roles) on nodes
#
# State commands run the role via main.yml with <role>_state=<state>.
# Task commands run tasks_from inside the role, bypassing main.yml.
#
# Usage: manage-feature.sh [-i INVENTORY] [-h HOST] [-y] [-K] <feature> <command> [extra-vars]
#
# State commands:
#   present      Install/deploy the feature
#   configure    Reconfigure without reinstalling (not all roles support this)
#   absent       Remove the feature
#
# Task commands (any tasks/<file>.yml in the role):
#   verify       Health check
#   <task>       Any task file in roles/<feature>/tasks/
#
# Examples:
#   source ~/.secrets/LabProvision
#   ./manage-feature.sh -h fleur fail2ban configure
#   ./manage-feature.sh -h fleur mail_agent present
#   ./manage-feature.sh -h fleur gitea verify
#   ./manage-feature.sh -h fleur sshd_harden present
#   ./manage-feature.sh -i inventory/hosts/fleur.yml fail2ban configure

set -euo pipefail

ANSIBLE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
INVENTORY="${SOLTI_INVENTORY:-}"
TEMP_DIR="${ANSIBLE_DIR}/tmp"
HOST=""
YES_FLAG=false
USE_SUDO=false
EXTRA_VARS=()

SUPPORTED_STATES=("present" "configure" "absent")

mkdir -p "${TEMP_DIR}"
chmod 700 "${TEMP_DIR}"

TEMP_PLAYBOOK=""
cleanup() {
    if [[ $? -eq 0 && -n "${TEMP_PLAYBOOK}" && -f "${TEMP_PLAYBOOK}" ]]; then
        rm -f "${TEMP_PLAYBOOK}"
    fi
}
trap cleanup EXIT INT TERM

# ── Feature discovery ─────────────────────────────────────────────────────────

discover_features() {
    find "${ANSIBLE_DIR}/roles" -maxdepth 1 -mindepth 1 -type d \
        ! -name '_*' ! -name 'shared' \
        -exec basename {} \; | sort
}

SUPPORTED_FEATURES=()
while IFS= read -r f; do
    SUPPORTED_FEATURES+=("$f")
done < <(discover_features)

# ── Helpers ───────────────────────────────────────────────────────────────────

usage() {
    cat <<EOF
Usage: $(basename "$0") [-i INVENTORY] [-h HOST] [-y] [-K] <feature> <command> [options]

Options:
  -i INVENTORY   Inventory file or directory (default: \$SOLTI_INVENTORY or inventory/hosts/)
  -h HOST        Target host
  -y             Skip safety prompts
  -K             Prompt for sudo password

State commands (run role main.yml):
  present        Install/enable the feature
  configure      Reconfigure in place (roles that support it)
  absent         Remove the feature

Task commands (run tasks/<task>.yml directly):
  verify         Health checks
  <task>         Any task file in the role's tasks/ directory

Features:
$(printf '  %s\n' "${SUPPORTED_FEATURES[@]}")

Examples:
  $(basename "$0") -h fleur fail2ban configure
  $(basename "$0") -h fleur mail_agent present
  $(basename "$0") -h fleur gitea verify
  $(basename "$0") -i inventory/hosts/fleur.yml sshd_harden present
EOF
    exit 1
}

is_state() {
    local cmd="$1"
    for s in "${SUPPORTED_STATES[@]}"; do
        [[ "$s" == "$cmd" ]] && return 0
    done
    return 1
}

is_feature_valid() {
    local feature="$1"
    for f in "${SUPPORTED_FEATURES[@]}"; do
        [[ "$f" == "$feature" ]] && return 0
    done
    return 1
}

target_hosts() {
    if [[ -n "${HOST}" ]]; then
        echo "${HOST}"
    else
        echo "all"
    fi
}

# ── Playbook generation ───────────────────────────────────────────────────────

generate_state_playbook() {
    local hosts; hosts=$(target_hosts)
    local feature_var; feature_var="${FEATURE/_/-}"
    local svar="${FEATURE}_state"

    TEMP_PLAYBOOK=$(mktemp "${TEMP_DIR}/manage-feature-XXXXXX.yml")
    cat > "$TEMP_PLAYBOOK" <<EOF
---
# Generated by manage-feature.sh: ${FEATURE} ${COMMAND}
- name: ${COMMAND} ${FEATURE}
  hosts: ${hosts}
  vars:
    ${svar}: ${COMMAND}
  roles:
    - role: ${FEATURE}
EOF
}

generate_task_playbook() {
    local hosts; hosts=$(target_hosts)

    TEMP_PLAYBOOK=$(mktemp "${TEMP_DIR}/manage-feature-XXXXXX.yml")
    cat > "$TEMP_PLAYBOOK" <<EOF
---
# Generated by manage-feature.sh: ${FEATURE}/${COMMAND}
- name: Execute ${COMMAND} for ${FEATURE}
  hosts: ${hosts}
  gather_facts: false
  tasks:
    - name: "${FEATURE}/${COMMAND}"
      ansible.builtin.include_role:
        name: "${FEATURE}"
        tasks_from: "${COMMAND}"
EOF
}

# ── Argument parsing ──────────────────────────────────────────────────────────

[[ $# -lt 1 ]] && usage

while [[ $# -gt 0 ]]; do
    case "$1" in
        -i) INVENTORY="$2"; shift 2 ;;
        -h) HOST="$2"; shift 2 ;;
        -y|--yes) YES_FLAG=true; shift ;;
        -K) USE_SUDO=true; shift ;;
        -e) EXTRA_VARS+=("-e" "$2"); shift 2 ;;
        -*) echo "Unknown option: $1"; usage ;;
        *) break ;;
    esac
done

[[ $# -lt 2 ]] && usage

FEATURE="$1"
COMMAND="$2"
shift 2

# Pass any remaining args as extra vars
while [[ $# -gt 0 ]]; do
    EXTRA_VARS+=("-e" "$1")
    shift
done

# ── Validation ────────────────────────────────────────────────────────────────

if ! is_feature_valid "${FEATURE}"; then
    echo "Unknown feature: ${FEATURE}"
    echo "Available features: ${SUPPORTED_FEATURES[*]}"
    exit 1
fi

if [[ -z "${INVENTORY}" ]]; then
    INVENTORY="${ANSIBLE_DIR}/inventory/hosts"
fi

if [[ ! -e "${INVENTORY}" ]]; then
    echo "Inventory not found: ${INVENTORY}"
    echo "Set SOLTI_INVENTORY or use -i, or create inventory/hosts/"
    exit 1
fi

# ── Confirm for destructive states ────────────────────────────────────────────

if [[ "${COMMAND}" == "absent" && "${YES_FLAG}" == false ]]; then
    echo "WARNING: This will remove ${FEATURE} from $(target_hosts)."
    read -r -p "Continue? [y/N] " reply
    [[ "${reply}" =~ ^[Yy]$ ]] || { echo "Aborted."; exit 0; }
fi

# ── Build and run ─────────────────────────────────────────────────────────────

ANSIBLE_ARGS=(-i "${INVENTORY}")
[[ "${USE_SUDO}" == true ]] && ANSIBLE_ARGS+=(-K)
ANSIBLE_ARGS+=("${EXTRA_VARS[@]}")

if is_state "${COMMAND}"; then
    generate_state_playbook
else
    generate_task_playbook
fi

echo "Running: ansible-playbook ${ANSIBLE_ARGS[*]} ${TEMP_PLAYBOOK}"
ansible-playbook "${ANSIBLE_ARGS[@]}" "${TEMP_PLAYBOOK}"
